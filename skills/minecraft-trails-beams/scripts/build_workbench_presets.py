"""Build browser-ready offline presets from validated Forge recipes."""
import copy,json,pathlib
from author_effect import ROOT,validate,validate_path

def stops(*colors):
    return [{'at':i/(len(colors)-1),'color':color,'alpha':alpha} for i,(color,alpha) in enumerate(colors)]

def main():
    base={name:json.loads((ROOT/'assets/presets'/f'{name}.json').read_text(encoding='utf8')) for name in ('blade','beam','helix')}
    default=json.loads((ROOT/'assets/forge-1.20.1/src/main/resources/assets/trailbeam/paths/custom.json').read_text(encoding='utf8'))
    def path(kind,**kw):return dict(default,kind=kind,**kw)
    pairs={
        'frost':{'label':'霜蓝双刃','recipe':base['blade'],'path':path('arc',amplitude=.9,branches=0)},
        'prism':{'label':'棱彩双芯束','recipe':base['beam'],'path':path('sine',amplitude=.23,cycles=1.5,branches=0)},
        'helix':{'label':'金色螺旋','recipe':base['helix'],'path':default},
    }
    flame=copy.deepcopy(base['blade']);flame['name']='Cinder whip';flame['layers'][0]['profile']='plasma';flame['layers'][0]['colors']=stops(('#641911',.05),('#F93D16',.5),('#FFCE4E',.9))
    flame['layers'][1]['colors']=stops(('#FF671B',.8),('#FFF0AD',1));flame['layers'][1]['profile']='pulse'
    pairs['flame']={'label':'熔火鞭痕','recipe':flame,'path':path('zigzag',amplitude=.75,cycles=3)}
    plasma=copy.deepcopy(base['beam']);plasma['name']='Violet plasma lash';plasma['layers'][0]['profile']='plasma';plasma['layers'][0]['width']=.42
    plasma['layers'][0]['colors']=stops(('#421684',.28),('#A746FF',.63),('#23F7F4',.38))
    plasma['layers'][1]['profile']='pulse';plasma['layers'][1]['repeat']=4.5
    pairs['plasma']={'label':'紫电鞭束','recipe':plasma,'path':path('zigzag',amplitude=.43,cycles=3.5,speed=.35)}
    runic=copy.deepcopy(base['helix']);runic['name']='Runic conduit';runic['section']='ribbon';runic['layers'][0]['profile']='rune';runic['layers'][0]['repeat']=3.0
    runic['layers'][0]['colors']=stops(('#13584E',.4),('#DCC46B',.9),('#FFE7A0',.35))
    pairs['rune']={'label':'符文牵引','recipe':runic,'path':path('arc',amplitude=.55,branches=0)}
    storm=copy.deepcopy(base['beam']);storm['name']='Forked storm beam';storm['section']='cross'
    storm['layers'][0]['profile']='plasma';storm['layers'][0]['colors']=stops(('#244E9B',.15),('#4C9BFF',.65),('#9FECFF',.4))
    storm['layers'][1]['profile']='pulse';storm['layers'][1]['colors']=stops(('#8ABEFF',.6),('#FFFFFF',1),('#D8FAFF',.7))
    pairs['storm']={'label':'分叉雷束','recipe':storm,'path':path('lightning',amplitude=.35,cycles=2.7,speed=.8,branches=3,branchLength=.55)}
    for name,p in pairs.items():
        validate(p['recipe']);validate_path(p['path'])
    target=ROOT/'assets/workbench/preset-data.js'
    target.write_text('/* Generated by scripts/build_workbench_presets.py. Do not edit by hand. */\n'+
        'globalThis.TRAIL_PRESETS = '+json.dumps(pairs,ensure_ascii=False,separators=(',',':'))+';\n'+
        'if (typeof module === "object" && module.exports) module.exports = globalThis.TRAIL_PRESETS;\n',encoding='utf8')
    print(json.dumps({'presets':len(pairs),'path':str(target)},ensure_ascii=False))

if __name__=='__main__':main()
